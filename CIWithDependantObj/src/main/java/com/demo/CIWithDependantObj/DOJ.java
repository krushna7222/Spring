package com.demo.CIWithDependantObj;

public class DOJ {

	
	  private int date,year;
	  private String month;
	public DOJ(int date, int year, String month) {
		super();
		this.date = date;
		this.year = year;
		this.month = month;
	}
	@Override
	public String toString() {
		return "DOJ [date=" + date + ", year=" + year + ", month=" + month + "]";
	}
	  
	  
	  
	  
	
}
